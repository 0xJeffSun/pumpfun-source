#!/usr/bin/env python3
"""[mg-P-raw] write deliveries/mg-P-raw-NN (never overwrites).
usage: mkdeliv.py NN BUILD_OUT SRC SUMMARY README_MD [--rawready JSON]
BUILD_OUT = pbuild.py output built WITH --ordered (result.json, score.json, unstripped.so, candidate.so, build.log,
link/replay.json -> the ordered.ld used)."""
import json, shutil, subprocess, sys, hashlib
from pathlib import Path
W = Path('/Users/shawwalters/Documents/Codex/2026-10-24/claude-pump-work'); T = Path(__file__).resolve().parent
BASE = W / 'base/L28'
nn, bo, src, summary, readme = sys.argv[1], Path(sys.argv[2]), Path(sys.argv[3]), sys.argv[4], Path(sys.argv[5])
d = W / 'deliveries' / ('mg-P-raw-%s' % nn)
assert not d.exists(), 'delivery exists: %s' % d
res = json.loads((bo / 'result.json').read_text()); sc = json.loads((bo / 'score.json').read_text())['summary']
rep = json.loads((bo / 'link/replay.json').read_text())
assert res['ok'] and res['runtime_valid'] and not sc['losses'] and not sc['raw_losses'] and sc['raw_gains']
d.mkdir(parents=True)
subprocess.run(['cp', '-c', '-R', str(src), str(d / 'src')], check=True)
p = subprocess.run(['diff', '-ruN', str(BASE / 'pump'), str(src)], capture_output=True, text=True)
(d / 'patch.diff').write_text(p.stdout)
files = sorted({l.split()[1].replace(str(BASE / 'pump') + '/', '') for l in p.stdout.splitlines() if l.startswith('diff -ruN')})
for f in ('unstripped.so', 'candidate.so', 'build.log', 'score.json', 'result.json'): shutil.copy2(bo / f, d / f)
(d / 'recipe').mkdir(); shutil.copy2(rep['ordered'], d / 'recipe/ordered.ld')
shutil.copytree(T, d / 'recipe/tools', ignore=shutil.ignore_patterns('__pycache__'))
(d / 'recipe/replay.json').write_text(json.dumps(rep, indent=1))
extra = {}
if '--rawready' in sys.argv:
    rr = json.loads(Path(sys.argv[sys.argv.index('--rawready') + 1]).read_text())
    shutil.copy2(sys.argv[sys.argv.index('--rawready') + 1], d / 'rawready.json')
    extra = dict(raw_ready=len(rr['ready']), raw_ready_matched=len(rr['per']))
dj = dict(lane='mg-P-raw', base_round='L28', base_unstripped_sha256=hashlib.sha256((BASE / 'unstripped.so').read_bytes()).hexdigest(),
          unstripped_sha256=res['unstripped_sha256'], candidate_sha256=res['candidate_sha256'], normalized=sc['normalized'], raw=sc['raw'],
          gains=sc['gains'], losses=sc['losses'], raw_gains=sc['raw_gains'], raw_losses=sc['raw_losses'], runtime_valid=res['runtime_valid'],
          stack_warnings=res['stack_warnings'], synthetic_layout=True, files_changed=files, summary=summary,
          patch_base=str(BASE / 'pump'), link_recipe='recipe/ordered.ld (generated by recipe/tools/pgen.py; build with recipe/tools/pbuild.py --ordered)',
          ordered_ld_sha256=hashlib.sha256((d / 'recipe/ordered.ld').read_bytes()).hexdigest(), **extra)
(d / 'delivery.json').write_text(json.dumps(dj, indent=1) + '\n')
shutil.copy2(readme, d / 'README.md')
print(d, json.dumps({k: dj[k] for k in ('normalized', 'raw', 'files_changed')}), len(dj['raw_gains']), 'raw gains')
