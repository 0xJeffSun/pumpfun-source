P32_1, P32_2, P32_3 = 0x9E3779B1, 0x85EBCA77, 0xC2B2AE3D
P64_1, P64_2, P64_3, P64_4, P64_5 = 0x9E3779B185EBCA87, 0xC2B2AE3D27D4EB4F, 0x165667B19E3779F9, 0x85EBCA77C2B2AE63, 0x27D4EB2F165667C5
r64 = lambda b, o: struct.unpack_from('<Q', b, o)[0]
r32 = lambda b, o: struct.unpack_from('<I', b, o)[0]
rotl = lambda x, r: ((x << r) | (x >> (64 - r))) & M
def avalanche(h):
    h ^= h >> 37; h = (h * 0x165667919E3779F9) & M; return h ^ (h >> 32)
def rrmxmx(h, n):
    h ^= rotl(h, 49) ^ rotl(h, 24); h = (h * 0x9FB21C651E98DF25) & M; h ^= (h >> 35) + n
    h = (h * 0x9FB21C651E98DF25) & M; return h ^ (h >> 28)
def fold(a, b):
    p = a * b; return (p & M) ^ (p >> 64)
def mix16(b, o, so):
    return fold(r64(b, o) ^ r64(SECRET, so), r64(b, o + 8) ^ r64(SECRET, so + 8))
def xxh3(b):
    n = len(b)
    if n == 0: return avalanche(0 ^ (r64(SECRET, 56) ^ r64(SECRET, 64)))  # unused
    if n <= 3:
        c1, c2, c3 = b[0], b[n >> 1], b[n - 1]
        comb = (c1 << 16) | (c2 << 24) | (c3 << 0) | (n << 8)
        bf = (r32(SECRET, 0) ^ r32(SECRET, 4)) & 0xffffffff
        keyed = comb ^ bf
        h = keyed  # XXH64_avalanche
        h ^= h >> 33; h = (h * P64_2) & M; h ^= h >> 29; h = (h * P64_3) & M; return h ^ (h >> 32)
    if n <= 8:
        i1, i2 = r32(b, 0), r32(b, n - 4)
        bf = (r64(SECRET, 8) ^ r64(SECRET, 16)) & M
        i64 = (i2 + (i1 << 32)) & M
        return rrmxmx(i64 ^ bf, n)
    if n <= 16:
        bf1 = r64(SECRET, 24) ^ r64(SECRET, 32); bf2 = r64(SECRET, 40) ^ r64(SECRET, 48)
        lo = r64(b, 0) ^ bf1; hi = r64(b, n - 8) ^ bf2
        sw = int.from_bytes(lo.to_bytes(8, 'little'), 'big')
        acc = (n + sw + hi + fold(lo, hi)) & M
        return avalanche(acc)
    if n <= 128:
        acc = (n * P64_1) & M
        if n > 32:
            if n > 64:
                if n > 96:
                    acc += mix16(b, 48, 96); acc += mix16(b, n - 64, 112)
                acc += mix16(b, 32, 64); acc += mix16(b, n - 48, 80)
            acc += mix16(b, 16, 32); acc += mix16(b, n - 32, 48)
        acc += mix16(b, 0, 0); acc += mix16(b, n - 16, 16)
        return avalanche(acc & M)
    raise ValueError('len > 128 not implemented')
def shard(piece):
    """lld MergeNoTailSection shard of a piece: SectionPiece.hash = uint32(xxh3_64) >> 1; shard = hash >> 26."""
    return ((xxh3(piece) & 0xffffffff) >> 1) >> 26
