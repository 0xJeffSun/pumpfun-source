#!/usr/bin/env python3
"""Recompute every claimed count of this packet from saved artifacts (read-only).

Checks, without running a compiler, linker, VM or network:
  1. saved artifacts decompress to their recorded SHA-256 values;
  2. the frontier baseline (repro/pump_amm/native-fee-cpi-recovery-20261027)
     and every saved layout candidate are measured with the repository's own
     AMM window measurement (same reader, key and raw test as
     repro/pump_amm/focused-diagnostics-20261026/measure.py);
  3. each layout keeps every baseline normalized and raw match (no loss) and
     the claimed counts hold;
  4. every ordered linker script differs from the captured SDK script only in
     the `.text` input-section selector list, and is regenerated byte-for-byte
     by tools/plan.py from the saved default-layout map and the frontier's
     own symbol artifact;
  5. stripped and symbol artifacts share identical .text bytes, the ordered
     text is a permutation of the default sections (same multiset of section
     sizes and same total size);
  6. runtime summaries are bound to the candidate SHA-256 with zero mismatches.
"""
import argparse, collections, gzip, hashlib, json, sys, tempfile
from pathlib import Path

P = Path(__file__).resolve().parent


def find_root():
    for p in [P, *P.parents]:
        if (p / 'evidence/original/pump_amm/deployed.so').is_file():
            return p
    raise SystemExit('repository root not found')


ROOT = find_root()
sys.path.insert(0, str(ROOT / 'repro/pump_amm/claim-self-transfer-v144/static-tool'))
sys.path.insert(0, str(P / 'tools'))
from elf_reader import Elf  # noqa: E402
import plan as planmod  # noqa: E402

sha = lambda b: hashlib.sha256(b).hexdigest()
FRONTIER = ROOT / 'repro/pump_amm/native-fee-cpi-recovery-20261027/results/build'


def measure(candidate, symbols):
    """Exact replica of focused-diagnostics measure.py row logic (no file output)."""
    original = Elf(ROOT / 'evidence/original/pump_amm/deployed.so')
    c, s = Elf(candidate), Elf(symbols)
    assert c.b[c.lo:c.hi] == s.b[s.lo:s.hi]
    index = collections.defaultdict(list)
    for f in s.funcs:
        st, size = f['start'], f['size']
        key = (size, sha(c.normalized[st:st + size]), json.dumps(c.pattern(st, size), sort_keys=True))
        index[key].append({'start': st, 'raw_sha256': sha(c.b[st:st + size])})
    entries = sorted(set(original.entries) | {original.lo})
    rows = []
    for st, en in zip(entries, entries[1:] + [original.hi]):
        m = index[(en - st, sha(original.normalized[st:en]), json.dumps(original.pattern(st, en - st), sort_keys=True))]
        raw = sha(original.b[st:en])
        rows.append({'start': st, 'size': en - st, 'normalized': bool(m), 'raw': any(x['raw_sha256'] == raw for x in m)})
    return rows


def counts(rows):
    return {'windows': len(rows), 'normalized_matches': sum(r['normalized'] for r in rows),
            'raw_matches': sum(r['raw'] for r in rows), 'unmatched': sum(not r['normalized'] for r in rows),
            'raw_matched_original_bytes': sum(r['size'] for r in rows if r['raw']),
            'normalized_matched_original_bytes': sum(r['size'] for r in rows if r['normalized'])}


def unpack(path, expect, tmp):
    data = gzip.decompress(path.read_bytes())
    assert sha(data) == expect, (path, sha(data), expect)
    out = Path(tmp) / path.name.replace('.gz', '')
    out.write_bytes(data)
    return out


def text_sections(path):
    return [(r['section'], planmod.selector_owner(r['owner']), r['size']) for r in planmod.parse_map(path)]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--skip-regenerate', action='store_true', help='skip regenerating ordered.ld with tools/plan.py')
    a = ap.parse_args()
    claims = json.loads((P / 'claims.json').read_text())
    report = {}
    with tempfile.TemporaryDirectory() as tmp:
        base_c, base_s = FRONTIER / 'candidate.so', FRONTIER / 'unstripped.so'
        assert sha(base_c.read_bytes()) == claims['baseline']['candidate_sha256']
        assert sha(base_s.read_bytes()) == claims['baseline']['symbols_sha256']
        base_rows = measure(base_c, base_s)
        report['baseline'] = counts(base_rows)
        assert report['baseline'] == claims['baseline']['counts'], report['baseline']
        default_script = (P / 'layout/sdk-default.ld').read_text()
        default_map = Path(tmp) / 'default.map'
        default_map.write_bytes(gzip.decompress((P / 'builds/default/link.map.gz').read_bytes()))
        default_text = text_sections(default_map)
        for name, rec in claims['layouts'].items():
            c = unpack(P / rec['candidate'], rec['candidate_sha256'], tmp)
            s = unpack(P / rec['symbols'], rec['symbols_sha256'], tmp)
            rows = measure(c, s)
            got = counts(rows)
            assert got == rec['counts'], (name, got, rec['counts'])
            lost_norm = [hex(x['start']) for x, y in zip(base_rows, rows) if x['normalized'] and not y['normalized']]
            lost_raw = [hex(x['start']) for x, y in zip(base_rows, rows) if x['raw'] and not y['raw']]
            gained_raw = [hex(x['start']) for x, y in zip(base_rows, rows) if y['raw'] and not x['raw']]
            assert not lost_norm and not lost_raw, (name, lost_norm, lost_raw)
            assert gained_raw == rec['gained_raw_windows'], name
            # linker script: only the .text selector list differs from the SDK script
            script = (P / rec['script']).read_text()
            head, tail = default_script.split('  .text : { *(.text*) } :text')
            assert script.startswith(head) and script.endswith(tail)
            body = script[len(head):len(script) - len(tail)]
            assert body.startswith('  .text : {\n') and body.endswith('\n    *(.text*)\n  } :text'), name
            for line in body.split('\n')[1:-2]:
                assert line.startswith('    *') and line.endswith('")') and '("' in line, line
            # text permutation check against the default map
            omap = Path(tmp) / (name + '.map')
            omap.write_bytes(gzip.decompress((P / rec['map']).read_bytes()))
            ordered_text = text_sections(omap)
            assert sorted(ordered_text) == sorted(default_text), name
            lo = Elf(s)
            assert lo.hi - lo.lo == sum(x[2] for x in default_text)
            if not a.skip_regenerate:
                pl = planmod.Plan(ROOT / 'evidence/original/pump_amm/deployed.so', base_s, default_map)
                pl.assign()
                seq, tl = pl.order()
                regen = pl.script(default_script, seq, tl)
                assert regen == script, name + ': regenerated script differs'
            rt = rec.get('runtime')
            if rt:
                summ = json.loads((P / rt).read_text())
                assert summ['candidate_sha256'] == rec['candidate_sha256'] and summ['mismatches'] == []
                assert summ['cases'] == 17462 and summ['suites'] == 25
            report[name] = dict(got, gained_raw=len(gained_raw), lost_raw=0, lost_normalized=0,
                                runtime_cases=(summ['cases'] if rt else None))
    print(json.dumps(report, indent=2))
    print('verified')


if __name__ == '__main__':
    main()
