#!/usr/bin/env python3
"""Standalone offline publication verification; not source or runtime certification."""
from pathlib import Path
import gzip,hashlib,json,sys
from analyze import analyze,verify_asm
P=Path(__file__).resolve().parent
H=lambda b:hashlib.sha256(b).hexdigest()
def read(n):return json.loads((P/n).read_text())
def main():
 manifest=read('manifest.json');owned=read('owned-map.json')
 actual={str(f.relative_to(P)) for f in P.rglob('*') if f.is_file()}
 assert not any(f.is_symlink() for f in P.rglob('*')),'symlink'
 assert actual==set(owned['files']),'unexpected/missing publication file'
 assert set(manifest)==actual-{'manifest.json','manifest.sha256'},'manifest inventory'
 assert (P/'manifest.sha256').read_text()==H((P/'manifest.json').read_bytes())+'  manifest.json\n','seal'
 for name,v in manifest.items():
  data=(P/name).read_bytes();assert len(data)==v['size'] and H(data)==v['sha256'],name
 for base in [P/'prior']+sorted((P/'prior/upstream').iterdir()):
  assert (base/'manifest.sha256').read_text().split()[0]==H((base/'manifest.json').read_bytes()),str(base)
 parent=read('prior/manifest.json')
 for b in read('input-bindings.json'):
  d=(P/b['path']).read_bytes();assert len(d)==b['size'] and H(d)==b['sha256'],b['path']
  if b.get('parent_member'):
   q=parent[b['parent_member']];assert (q if isinstance(q,str) else q['sha256'])==H(d),b['path']
   if isinstance(q,dict):assert q['size']==len(d)
 assert analyze()==read('byte-ledger.json'),'regenerated byte ledger'
 n=verify_asm()
 rows={r['start']:r for r in read('byte-ledger.json')['rows']}
 ins={i['pc']:i for r in rows.values() for i in r['instructions']}
 calls={0x1488c0:0x83c00,0x83c70:0xa0bf0,0x83ed8:0x8f5c8,0x840a0:0xa1bd8,0x84138:0xa1bd8,0x841d8:0x81848,0x846d8:0x97930,0x979b8:0x8df98,0x97ba8:0x91ef0,0x84760:0x965b8,0x84810:0x92820,0x8fdd8:0x17fcc8,0x93018:0x17fcc8,0x17fd58:0x1936d0,0x193820:0x191338,0x1489d8:0x859b0,0x128978:0x107b38}
 for pc,t in calls.items():assert ins[pc]['call']['target']==t,hex(pc)
 for pc,t in {0x83fa0:0x84468,0x84588:0x83fa8,0x84010:0x84068,0x1488d8:0x148920}.items():assert ins[pc]['branch_target']==t
 # Actual relocation bindings, not apparent self-call operands.
 assert ins[0x1b3690]['call']['symbols']==['sol_memcmp_']
 assert ins[0x1a2068]['call']['symbols']==['sol_invoke_signed_rust']
 receipt=json.loads(gzip.decompress((P/'evidence/v3_configured_fee.json.gz').read_bytes()))
 saved=read('prior/preservation-ledger.json');reg={r['index']:r for r in read('evidence/regressions.json')}
 indexes=[i for i,r in enumerate(receipt['cases']) if r['case']['operation']=='buy_v3']
 assert indexes==[r['index'] for r in saved['rows']] and len(indexes)==117
 success=0
 for s in saved['rows']:
  row=receipt['cases'][s['index']];old=reg[s['index']]
  assert H(json.dumps(row,sort_keys=True,separators=(',',':')).encode())==s['saved_row_sha256']
  assert row['case']==old['case']==s['case'] and row['match'] is True
  assert row['original']['error']==old['original_error']==s['original_error']
  assert s['base_mint_owner']==old['base_mint_owner']=='TokenzQdBNbLqP5VEhdkAS6EPFLC1PHnBqCXEpPxuEb'
  assert s['base_mint_size']==old['base_mint_size']
  key=s['volume_key'];v=row['original']['accounts'][key]
  assert v==row['candidate']['accounts'][key] and len(bytes.fromhex(v['data_hex']))==137
  success+=row['original']['error'] is None
 assert success==105 and len(indexes)-success==12
 assert len(read('prior/obligations.json'))==8
 result=read('result.json');assert not result['B6_complete'] and not result['integratable'] and not result['proposal_preservation_proven']
 assert result['new_runtime_tests']==result['new_fixtures']==0
 # Source fragment integrity is sealed; these checks only constrain proposal scope.
 assert 'buy_domain(a)?' in (P/'prior/proposed-buy.rs').read_text()
 assert 'token::ID' in (P/'prior/proposed-buy_v3_admission.rs').read_text() or 'spl_token::ID' in (P/'prior/proposed-buy_v3_admission.rs').read_text()
 data=read('data-contract.json')
 from elf_reader import ELF
 e=ELF(P/'evidence/original.so')
 for r in data['objects']:assert e.at(r['address'],r['length']).hex()==r['bytes']
 print(json.dumps({'status':'PASS','assembly_instructions_checked':n,'inferred_intervals':len(rows),'historical_rows':117,'historical_successes':105,'runtime_execution':False,'B6_complete':False}))
if __name__=='__main__':
 try:main()
 except Exception as ex:
  print('FAIL: '+str(ex),file=sys.stderr);sys.exit(1)
